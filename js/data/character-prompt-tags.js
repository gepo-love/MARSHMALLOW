export function normalizeCharacterPromptTags(value = []) {
  const list = Array.isArray(value)
    ? value
    : String(value || '').split(/[,，/|、\s]+/);
  const valid = new Set(Object.keys(CHARACTER_PROMPT_TAGS));
  return [...new Set(list.map((x) => String(x || '').trim()).filter((x) => valid.has(x)))];
}

export function getCharacterPromptTagSnippets(ids = []) {
  return normalizeCharacterPromptTags(ids)
    .map((id) => CHARACTER_PROMPT_TAGS[id]?.content)
    .filter(Boolean);
}
