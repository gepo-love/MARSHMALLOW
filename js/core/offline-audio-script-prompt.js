import { buildNarrationStyleGuard } from './narration-style-guard.js';

/** 音声线下专用正文协议；共同记忆、连续状态和媒体隐藏块仍复用线下底层。 */
export function buildOfflineAudioScriptPrompt({
  wordMin = 200,
  wordMax = 500,
  hasUserInput = false,
} = {}) {
  return [
    '【音声线下 · 旁白＋角色对白脚本】这是独立于普通约会探索的音声演出模式。可见正文必须由静音旁白与角色直接对白共同构成，不写聊天气泡，也不写“角色名：台词”的剧本标签。',
    '旁白固定用第二人称“你”称呼用户，只负责镜头、环境、角色动作、距离变化、可听见的呼吸与音效落点；旁白永远不进入语音轨。段落保持短而可视化，避免连续大段心理分析或小说式总结。',
    '角色对白使用自然引号（中文“……”或日文「……」）明确落在正文中，是唯一允许朗读的内容；不要用 [台词]、【对白】等方括号格式。对白需要推动当下互动，并与角色的动作、停顿、气息和距离变化交替出现；除非本拍刻意沉默，不要让整轮只剩旁白。',
    '结构必须像 Galgame 分镜一样清楚：每个旁白拍点单独成段，每句角色直接对白也单独成段，按“旁白→对白→旁白→对白”交替推进；严禁把旁白和对白混在同一段，严禁连续堆成长篇小说段落。',
    buildNarrationStyleGuard({ surface: 'audio' }),
    '语音表演必须属于角色本人：颤音、停顿、换气、轻喘、笑意、压低声线等写入语音隐藏结构或角色周围的静音旁白，不能把这些声音安到用户身上，也不能朗读括号舞台说明。',
    hasUserInput
      ? '用户本轮输入已经是用户亲口说出的对白；正文不得复述、润色或替用户再说一遍，只从角色听见后的动作、气息与回应开始。'
      : '用户本轮没有输入；让角色与环境自然推进一个可回应的新拍点，不替用户补台词、心理或决定。',
    `篇幅控制在 ${wordMin}~${wordMax} 字：以数个短旁白段和角色对白交替组织，保持音声节奏，不套用普通线下“长旁白、少量对白”的写法。`,
    '结尾停在角色刚完成的动作、说完的一句话或环境发生的变化上，给用户留下可以直接说话回应的空间；不要写“等待你的回答”。',
  ].join('\n');
}
