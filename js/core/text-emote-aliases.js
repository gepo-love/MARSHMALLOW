const EMOTE_BRACKET_RE = /\[([^\[\]\n]{1,12})\]/g;

export function expandTextEmoteAliases(text = '') {
  const input = String(text ?? '');
  if (!input || !input.includes('[')) return input;
  return input.replace(EMOTE_BRACKET_RE, (full, rawName) => {
    const name = String(rawName || '').trim();
    if (!name) return full;
    // 留给表情包标签： [表情包:xx] / [贴纸:xx]
    if (/^(?:表情包|贴纸)\s*[:：]/.test(name)) return full;
    const hit = TEXT_EMOTE_ALIASES[name];
    return hit || full;
  });
}

export function listTextEmoteAliasHints(limit = 24) {
  return Object.entries(TEXT_EMOTE_ALIASES)
    .slice(0, Math.max(1, Number(limit) || 24))
    .map(([name, emoji]) => `[${name}]→${emoji}`);
}
